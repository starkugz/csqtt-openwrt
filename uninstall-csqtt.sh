#!/bin/sh
# ================================================================
#  CSQTT OpenWrt — uninstall-csqtt.sh: удаление клиента с роутера.
#
#  Удаляет пакеты CSQTT (в порядке зависимостей):
#    - luci-app-csqtt     — панель LuCI (star-panel-csqtt); с v1.1.1 несёт
#                           ВСТРОЕННЫЙ русский словарь (luci-i18n-csqtt-ru не
#                           требуется);
#    - luci-i18n-csqtt-ru — отдельный пакет перевода: только для legacy-установок
#                           (до v1.1.1). На новых установках отсутствует и
#                           пропускается;
#    - csqtt-core-2.1.9   — ядро 2.1.9 с управлением (самостоятельный пакет);
#    - csqtt-core-2.5.0   — ядро 2.5.0 с управлением (самостоятельный пакет).
#  [008] Отдельного управляющего пакета `csqtt` больше нет: служба, UCI, init.d
#  и CLI входят в каждый пакет ядра, а общие точки входа создаёт activate.sh
#  активного ядра. Имя `csqtt` оставлено в списке только для миграции с
#  установок прежней (четырёхпакетной) раскладки.
#  Отсутствующие пакеты (например, ненужное ядро или legacy-перевод) просто
#  пропускаются.
#
#  Поддерживаются оба менеджера пакетов:
#    - apk  (OpenWrt 25.12.x / SNAPSHOT);
#    - opkg (OpenWrt 24.10.x).
#
#  Принципы:
#    - останавливает службу (/etc/init.d/csqtt stop) и снимает автозапуск
#      (disable); ошибка любой из этих операций НЕ даёт ложного полного успеха —
#      удаление продолжается, но итог и код возврата ненулевые (D6);
#    - скрипт просит удалить только свои пакеты (перечислены имена, autoremove /
#      cleanup / --recursive не передаются) и никогда не называет чужие пакеты.
#      Но apk (OpenWrt 25.12+) по своей семантике `apk del` дополнительно
#      убирает автоматически установленные зависимости, которые больше никому не
#      нужны; зависимости, нужные другим пакетам или базовой системе, остаются.
#      opkg (24.10) зависимости не трогает. Проверено на apk-tools 3.0.5;
#    - отсутствующие пакеты пропускаются; реальные ошибки удаления не
#      скрываются и приводят к ненулевому коду возврата;
#    - конфигурация /etc/config/csqtt перед удалением копируется в уникальный
#      защищённый временный каталог (mktemp -d, права 0700) и восстанавливается,
#      если менеджер её снёс (каталог конфигурации при необходимости создаётся
#      заново); если копию создать не удалось — удаление НЕ начинается; при
#      ошибке восстановления копия НЕ удаляется;
#    - относится только к клиенту OpenWrt: серверную часть на VPS не
#      затрагивает, маршрутизацию, DNS, firewall, Mihomo, Podkop и другие
#      приложения не изменяет.
#
#  Запуск (от root):
#    sh uninstall-csqtt.sh
#    wget --no-proxy -qO- https://github.com/starkugz/csqtt-openwrt/raw/refs/heads/main/uninstall-csqtt.sh | ash
#
#  Локальные тесты (НЕ роутер): CSQTT_ROOT=<каталог> подменяет корень файловой
#  системы, TMPDIR — каталог резервных копий. См. openwrt/tests/uninstall/.
# ================================================================
set -u

# Переопределяемый корень (для локальных тестов; на роутере пусто).
ROOT="${CSQTT_ROOT:-}"
CFG="${ROOT}/etc/config/csqtt"
INIT="${ROOT}/etc/init.d/csqtt"
PKGS="luci-i18n-csqtt-ru luci-app-csqtt csqtt-core-2.1.9 csqtt-core-2.5.0 csqtt"

rc=0
KEEP_DIR=
KEEP=

log()  { echo "CSQTT: $*"; }
warn() { echo "CSQTT: $*" >&2; }

# --- права root -------------------------------------------------
if [ "$(id -u 2>/dev/null)" != 0 ]; then
	warn "нужны права root."
	exit 1
fi

# --- менеджер пакетов -------------------------------------------
PM=
if command -v apk >/dev/null 2>&1; then
	PM=apk
elif command -v opkg >/dev/null 2>&1; then
	PM=opkg
else
	warn "не найден ни apk, ни opkg."
	exit 1
fi
log "менеджер пакетов: $PM"

# --- резервная копия конфигурации -------------------------------
# Копию создаём ДО любых изменений; если создать не удалось — не начинаем.
umask 077
if [ -f "$CFG" ]; then
	KEEP_DIR=$(mktemp -d "${TMPDIR:-/tmp}/csqtt-uninstall.XXXXXX") || KEEP_DIR=
	if [ -z "$KEEP_DIR" ]; then
		warn "не удалось создать временный каталог для резервной копии."
		warn "удаление не начато."
		exit 1
	fi
	KEEP="$KEEP_DIR/csqtt.config"
	if ! cp -p "$CFG" "$KEEP"; then
		warn "не удалось сохранить резервную копию $CFG."
		warn "удаление не начато."
		rm -rf "$KEEP_DIR"
		exit 1
	fi
	log "резервная копия конфигурации: $KEEP"
fi

# --- остановка службы и снятие автозапуска ----------------------
# [D6] Ошибка `stop`/`disable` — это НЕ полный успех: пакеты всё равно удаляем
# (частичное удаление полезнее отказа), но итог и код возврата обязаны отражать
# факт. Иначе скрипт рапортовал «готово: CSQTT удалён», пока процесс мог
# продолжать работать, а автозапуск остаться включённым (живой дефект 2026-10-15).
if [ -x "$INIT" ]; then
	if ! "$INIT" stop; then
		warn "не удалось остановить службу: процесс может продолжать работать."
		rc=1
	fi
	if ! "$INIT" disable; then
		warn "не удалось снять автозапуск: служба может стартовать при загрузке."
		rc=1
	fi
fi

# --- удаление только своих пакетов ------------------------------
for p in $PKGS; do
	if [ "$PM" = apk ]; then
		if apk info -e "$p" >/dev/null 2>&1; then
			apk del "$p" || { warn "не удалось удалить $p."; rc=1; }
		else
			log "$p не установлен — пропуск."
		fi
	else
		if opkg list-installed 2>/dev/null | grep -q "^$p - "; then
			opkg remove "$p" || { warn "не удалось удалить $p."; rc=1; }
		else
			log "$p не установлен — пропуск."
		fi
	fi
done

# --- сохранение конфигурации ------------------------------------
if [ -n "$KEEP" ] && [ -f "$KEEP" ]; then
	if [ -f "$CFG" ]; then
		rm -rf "$KEEP_DIR"
	else
		if mkdir -p "$(dirname "$CFG")" && cp -p "$KEEP" "$CFG"; then
			log "конфигурация восстановлена из резервной копии ($CFG)."
			rm -rf "$KEEP_DIR"
		else
			# Копию НЕ удаляем: она нужна для ручного восстановления.
			warn "не удалось восстановить конфигурацию; резервная копия сохранена: $KEEP"
			rc=1
		fi
	fi
fi

# --- итог -------------------------------------------------------
if [ "$rc" = 0 ]; then
	log "готово: CSQTT удалён, настройки сохранены."
else
	warn "удаление завершено с ошибками (см. сообщения выше)."
fi
exit $rc
